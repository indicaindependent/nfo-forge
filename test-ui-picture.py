import asyncio, re
from playwright.async_api import async_playwright
URL="http://localhost:8765/index.html"
async def main():
    errs=[]; res=[]
    def ok(n,c,x=""): res.append(bool(c)); print(("PASS " if c else "FAIL ")+n+(" -> "+str(x)[:160] if (x and not c) else ""))
    async with async_playwright() as p:
        b=await p.chromium.launch(); ctx=await b.new_context(viewport={"width":1500,"height":1100},accept_downloads=True); pg=await ctx.new_page()
        pg.on("console",lambda m: errs.append(m.text) if m.type=="error" else None)
        pg.on("pageerror",lambda e: errs.append(str(e)))
        await pg.goto(URL); await pg.wait_for_timeout(500)
        ok("picture panel hidden at start", await pg.is_hidden("#picturePanel"))
        ok("text editor visible at start", await pg.is_visible("#editorPanel"))
        await pg.click("#tabPic"); await pg.wait_for_timeout(200)
        ok("picture panel shown after tab click", await pg.is_visible("#picturePanel"))
        ok("text editor hidden in picture tab", await pg.is_hidden("#editorPanel"))
        ok("5 styles listed", await pg.locator("#picMode option").count()==5, await pg.locator("#picMode option").count())
        ok("aria-pressed set", await pg.get_attribute("#tabPic","aria-pressed")=="true")
        ok("prompt before any image", "Choose an image" in await pg.inner_text("#status"), await pg.inner_text("#status"))
        await pg.set_input_files("#picFile","/tmp/pic-test.png"); await pg.wait_for_timeout(500)
        out=await pg.inner_text("#out"); lines=out.rstrip("\n").split("\n")
        ok("painted preview appears", len(lines)>5, len(lines))
        ok("width 76 respected", all(len(l)==76 for l in lines), sorted(set(len(l) for l in lines)))
        ok("painted mode is keyboard ASCII only", all(32<=ord(c)<=126 for l in lines for c in l), [c for l in lines for c in l if not 32<=ord(c)<=126][:5])
        ok("painted mode uses varied symbols", len(set(out)-{" ","\n"})>=12, len(set(out)-{" ","\n"}))
        for m in ["shade","half","ramp","edge","paint"]:
            await pg.select_option("#picMode",m); await pg.wait_for_timeout(250)
            o=(await pg.inner_text("#out")).rstrip("\n").split("\n")
            ok(f"style {m}: renders, uniform width", len(o)>3 and len(set(len(l) for l in o))==1, sorted(set(len(l) for l in o)))
        await pg.fill("#picCols","50"); await pg.dispatch_event("#picCols","input"); await pg.wait_for_timeout(250)
        o=(await pg.inner_text("#out")).rstrip("\n").split("\n"); ok("width change to 50", all(len(l)==50 for l in o), sorted(set(len(l) for l in o)))
        await pg.fill("#picCols","76"); await pg.dispatch_event("#picCols","input")
        await pg.select_option("#picMode","half"); await pg.check("#picColour"); await pg.wait_for_timeout(300)
        spans=await pg.locator("#out span").count(); ok("colour preview uses coloured spans", spans>10, spans)
        ok("status explains .ans", ".ans" in await pg.inner_text("#status"), await pg.inner_text("#status"))
        # downloads
        await pg.fill("#picTitle","Test Picture"); await pg.fill("#picAuthor","Tester"); await pg.fill("#picGroup","Grp")
        async with pg.expect_download() as d: await pg.click("#picDlAns")
        dl=await d.value; path="/tmp/pic-dl.ans"; await dl.save_as(path)
        ok("ans filename is slug.ans", dl.suggested_filename=="test-picture.ans", dl.suggested_filename)
        raw=open(path,"rb").read()
        ok("ans has SAUCE record", b"SAUCE00" in raw[-140:], raw[-140:][:12])
        ok("ans has EOF 0x1A before SAUCE", b"\x1aSAUCE00" in raw or b"\x1a" in raw[-130:-125] or raw.rfind(b"SAUCE00")>0 and raw[raw.rfind(b"SAUCE00")-1]==0x1a)
        ok("ans contains ESC[ colour codes", b"\x1b[" in raw)
        await pg.uncheck("#picColour"); await pg.select_option("#picMode","paint"); await pg.wait_for_timeout(250)
        async with pg.expect_download() as d2: await pg.click("#picDlTxt")
        d2v=await d2.value; await d2v.save_as("/tmp/pic-dl.txt"); t=open("/tmp/pic-dl.txt").read()
        ok("txt filename", d2v.suggested_filename=="test-picture.txt", d2v.suggested_filename)
        ok("txt matches preview exactly", t.rstrip("\n")==(await pg.inner_text("#out")).rstrip("\n"))
        async with pg.expect_download() as d3: await pg.click("#picDlNfo")
        d3v=await d3.value; await d3v.save_as("/tmp/pic-dl.nfo"); nraw=open("/tmp/pic-dl.nfo","rb").read()
        ok("nfo filename", d3v.suggested_filename=="test-picture.nfo", d3v.suggested_filename)
        ok("nfo has SAUCE", b"SAUCE00" in nraw[-140:])
        # back to text tab: the original flow still works
        await pg.click("#tabText"); await pg.wait_for_timeout(300)
        ok("back to text tab hides picture panel", await pg.is_hidden("#picturePanel"))
        ok("text preview restored", "YOUR RELEASE NAME" in await pg.inner_text("#out"), (await pg.inner_text("#out"))[:60])
        # bad file
        await pg.click("#tabPic"); open("/tmp/not-an-image.txt","w").write("hello")
        await pg.set_input_files("#picFile","/tmp/not-an-image.txt"); await pg.wait_for_timeout(300)
        ok("non-image rejected with a message", "not an image" in (await pg.inner_text("#status")).lower(), await pg.inner_text("#status"))
        # mobile
        await pg.set_viewport_size({"width":390,"height":800}); await pg.wait_for_timeout(200)
        ok("no horizontal overflow at 390px in picture tab", await pg.evaluate("document.documentElement.scrollWidth<=document.documentElement.clientWidth+1"), await pg.evaluate("document.documentElement.scrollWidth"))
        ok("no console errors", not errs, errs[:3])
        await b.close()
    print(f"\n{sum(res)} passed, {len(res)-sum(res)} failed"); raise SystemExit(0 if all(res) else 1)
asyncio.run(main())
